const ROWS = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(' ')]));

export const textWidth = (s, scale = 1) => s.length ? (s.length * 6 - 1) * scale : 0;

/* Draws `s` with its top-left at (x, y) in logical pixels; `outline` adds a 1px dark border for legibility. */
export function drawText(ctx, s, x, y, { color = '#fff', scale = 1, outline = null } = {}){
  s = String(s).toUpperCase(); x = Math.round(x); y = Math.round(y);
  const paint = (c, ox, oy) => {
    ctx.fillStyle = c;
    for (let i = 0; i < s.length; i++){
      const g = ROWS[s[i]] || ROWS['?'], gx = x + i * 6 * scale + ox;
      for (let r = 0; r < 7; r++) for (let col = 0; col < 5; col++)
        if (g[r][col] === '1') ctx.fillRect(gx + col * scale, y + r * scale + oy, scale, scale);
    }
  };
  if (outline) for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) paint(outline, ox, oy);
  paint(color, 0, 0);
}

export function drawTextCentered(ctx, s, cx, y, opts = {}){
  drawText(ctx, s, cx - textWidth(String(s), opts.scale || 1) / 2, y, opts);
}
